-- Public views are still protected by underlying RLS because security_invoker is enabled.
create or replace view public.campaign_summary
with (security_invoker = true)
as
select
  c.id as campaign_id,
  c.name,
  c.target_vgv,
  coalesce(sum(s.vgv) filter (where s.status = 'signed'),0)::numeric as confirmed_vgv,
  coalesce(sum(s.vgv) filter (where s.status = 'pending'),0)::numeric as pending_vgv,
  coalesce(sum(s.vgv) filter (where s.status in ('signed','pending')),0)::numeric as total_vgv,
  count(*) filter (where s.status = 'signed')::int as signed_contracts,
  count(*) filter (where s.status in ('signed','pending'))::int as total_sales,
  count(*) filter (where s.status in ('signed','pending'))::int as total_units,
  count(distinct s.operator_id) filter (where s.status = 'signed')::int as decorated_operators,
  (select count(*)::int from public.operators o where o.active) as active_operators
from public.campaigns c
left join public.sales s on s.campaign_id = c.id and s.status <> 'cancelled'
where c.active = true
group by c.id, c.name, c.target_vgv;

create or replace view public.operator_performance
with (security_invoker = true)
as
select
  o.id,
  o.full_name,
  o.codename,
  o.title,
  t.name as team_name,
  coalesce(p.avatar_path, o.avatar_path) as avatar_path,
  coalesce(p.selected_loadout, 'assault') as selected_loadout,
  coalesce(sum(s.vgv) filter (where s.status = 'signed'),0)::numeric as vgv,
  count(s.id) filter (where s.status = 'signed')::int as sales_count,
  count(s.id) filter (where s.status = 'signed')::int as units_count,
  case when count(s.id) filter (where s.status='signed') > 0 then 'signed'
       when count(s.id) filter (where s.status='pending') > 0 then 'wait'
       else 'field' end as status
from public.operators o
left join public.teams t on t.id = o.team_id
left join public.profiles p on p.operator_id = o.id
left join public.sales s on s.operator_id = o.id
  and s.campaign_id = (select id from public.campaigns where active = true order by start_date desc limit 1)
  and s.status <> 'cancelled'
where o.active = true
group by o.id, o.full_name, o.codename, o.title, t.name, p.avatar_path, o.avatar_path, p.selected_loadout;

grant select on public.campaign_summary, public.operator_performance to authenticated;

