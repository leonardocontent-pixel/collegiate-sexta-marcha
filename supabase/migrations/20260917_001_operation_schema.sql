-- Collegiate Vendas / Operação Sexta Marcha
create extension if not exists pgcrypto;

create table if not exists public.teams (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  slug text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.operators (
  id uuid primary key default gen_random_uuid(),
  full_name text not null,
  codename text not null,
  title text not null default 'Executivo de Vendas',
  team_id uuid references public.teams(id) on delete set null,
  avatar_path text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'executive' check (role in ('admin','manager','executive')),
  active boolean not null default true,
  team_id uuid references public.teams(id) on delete set null,
  operator_id uuid unique references public.operators(id) on delete set null,
  selected_loadout text not null default 'assault',
  avatar_path text,
  avatar_crop jsonb not null default '{"zoom":1.25,"x":0,"y":0}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.campaigns (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  subtitle text,
  target_vgv numeric(14,2) not null default 0,
  start_date date not null,
  end_date date not null,
  active boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.sales (
  id uuid primary key default gen_random_uuid(),
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  operator_id uuid not null references public.operators(id) on delete cascade,
  development text not null,
  unit text,
  customer_name text,
  vgv numeric(14,2) not null check (vgv >= 0),
  commission_rate numeric(7,5) not null default 0.03,
  status text not null default 'pending' check (status in ('pending','signed','cancelled')),
  signed_at date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.loadouts (
  id uuid primary key default gen_random_uuid(),
  key text not null unique,
  name text not null,
  tagline text,
  description text,
  stats jsonb not null default '[1,1,1,0]'::jsonb,
  sort_order int not null default 0,
  active boolean not null default true
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity text not null,
  entity_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists sales_campaign_idx on public.sales(campaign_id);
create index if not exists sales_operator_idx on public.sales(operator_id);
create index if not exists sales_signed_at_idx on public.sales(signed_at);
create index if not exists profiles_team_idx on public.profiles(team_id);
create index if not exists operators_team_idx on public.operators(team_id);

create or replace function public.current_role()
returns text
language sql
stable
security definer
set search_path = public, pg_temp
as $$ select role from public.profiles where id = auth.uid() $$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email,'@',1)))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

